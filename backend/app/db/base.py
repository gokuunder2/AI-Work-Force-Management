# uuid: used for the type of the random IDs
import uuid
# datetime: the Python type for created_at / updated_at values
from datetime import datetime

# DateTime / func: column type and database functions (now(), gen_random_uuid())
from sqlalchemy import DateTime, func
# PostgreSQL's native UUID column type
from sqlalchemy.dialects.postgresql import UUID
# DeclarativeBase: parent of all tables; Mapped/mapped_column: define typed columns
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


# BASE: every table class inherits from this so SQLAlchemy knows about it
class Base(DeclarativeBase):
    pass


# Adds a random UUID primary key called "id" to a table
class UUIDPrimaryKeyMixin:
    # Generated by the app (uuid4) and, as a fallback, by the database (gen_random_uuid())
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=func.gen_random_uuid(),
    )


# Adds created_at / updated_at timestamps to a table
class TimestampMixin:
    # When the row was created. The database fills it in automatically.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    # When the row was last updated. Set by the database on every update.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
